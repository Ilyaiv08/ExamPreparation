/**
 * Объяснение дней плана простыми словами.
 *
 * Зачем это нужно. В учебной программе день записан телеграфно и для того,
 * кто уже в теме: «Flexbox: `display: flex`, `justify-content`, `align-items`».
 * Новичку такая строка не говорит ничего — это список слов, а не объяснение.
 *
 * Поэтому у каждого дня есть два текста:
 *  - дословный из программы (поля theory/practice объекта дня) — он не меняется
 *    ни при каких обстоятельствах, это первоисточник;
 *  - человеческий (этот файл) — что сегодня изучаем, что будем делать руками
 *    и зачем это на экзамене.
 *
 * Платформа показывает человеческий текст первым, а формулировку программы —
 * рядом, отдельным блоком. Подменять одно другим нельзя: студент должен видеть
 * и то, что написано в программе, и что это значит.
 */

export interface DayNote {
  /** Короткое название дня человеческим языком. */
  title: string;
  /** Что сегодня изучаем. Два-три предложения, без списка терминов. */
  theory: string;
  /** Что делаем руками. Конкретный результат дня. */
  practice: string;
  /** Зачем это на экзамене. Необязательно — только там, где связь неочевидна. */
  why?: string;
}

